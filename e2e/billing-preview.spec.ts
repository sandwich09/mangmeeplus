import { test, expect } from './harness/fixtures';

for (const width of [1280, 390]) test(`BILLING-PREVIEW full journey uses no billing mutations at ${width}px`, async ({ authedPage: page, companyId }, info) => {
  await page.setViewportSize({ width, height: 900 });
  const forbiddenRequests: string[] = [];
  page.on('request', request => {
    if ((request.method() !== 'GET' && /\/billing(?:\/|$)/.test(new URL(request.url()).pathname)) || new URL(request.url()).hostname.endsWith('stripe.com')) forbiddenRequests.push(request.url());
  });
  await page.goto(`/companies/${companyId}/billing`);
  await page.getByRole('link', { name: 'พรีวิวขั้นตอน (local)', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'พรีวิวทุกขั้นตอน · เฉพาะ local', exact: true })).toBeVisible();
  const scenario = page.getByLabel('เลือกหน้าจอที่ต้องการดู', { exact: true });
  const plans = page.getByRole('region', { name: 'เลือกแพ็กเกจ', exact: true });
  await expect(plans).toBeVisible();
  await plans.getByRole('button', { name: 'รายปี', exact: true }).click();
  await expect(plans.getByText('เร็ว ๆ นี้', { exact: true })).toBeDisabled();
  await expect(plans).toContainText('ใช้งาน 12 เดือน · ประหยัด ฿498.00');
  await plans.getByRole('button', { name: 'เลือกแพ็กเกจนี้', exact: true }).first().click();
  await expect(page.getByRole('heading', { name: /^ยืนยันซื้อ .* รายปี$/ })).toBeVisible();
  await expect(plans).toHaveCount(0);
  const quoteHeading = await page.getByRole('heading', { name: /^ยืนยันซื้อ .* รายปี$/ }).boundingBox();
  expect(quoteHeading!.y).toBeGreaterThanOrEqual(width < 640 ? 112 : 68);
  const checkout = page.getByRole('button', { name: 'ยืนยันและไปชำระที่ Stripe', exact: true });
  await expect(checkout).toBeDisabled();
  await page.getByLabel('ฉันตรวจสอบข้อมูลและยืนยันเงื่อนไขการชำระเงินและต่ออายุอัตโนมัติ', { exact: true }).check();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: info.outputPath(`billing-preview-review-${width}.png`), fullPage: true });
  await checkout.click();
  await expect(page.getByRole('heading', { name: 'จำลองหน้าชำระเงินภายนอก', exact: true })).toBeVisible();
  await expect(page.locator('input')).toHaveCount(0);
  await page.getByRole('button', { name: 'จำลองชำระสำเร็จ', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'ชำระแล้ว เปิดใช้งานแล้ว', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'กลับไปยังรายการเดิม', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'ตรวจผลการชำระเงินอีกครั้ง', exact: true })).toHaveCount(0);
  await expect(page.getByRole('region', { name: 'จัดการการต่ออายุ', exact: true })).toHaveCount(0);
  await expect(plans).toHaveCount(0);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: info.outputPath(`billing-overview-clean-${width}.png`), fullPage: true });
  await page.getByRole('button', { name: 'ประวัติ', exact: true }).click();
  await expect(page.getByRole('region', { name: 'ประวัติการชำระเงิน', exact: true })).toContainText('PREVIEW-0001');
  await page.getByRole('button', { name: 'ดูเอกสาร', exact: true }).click();
  await page.getByRole('button', { name: 'เปิดใบเสร็จรับเงิน', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'ใบเสร็จรับเงินตัวอย่าง', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'กลับไปประวัติการชำระเงิน', exact: true }).click();
  await page.getByRole('button', { name: 'ดูเอกสาร', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'เอกสารการชำระเงิน', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'กลับไปประวัติการชำระเงิน', exact: true }).click();
  await page.getByRole('button', { name: 'การต่ออายุและชำระเงิน', exact: true }).click();
  await page.getByRole('button', { name: 'หยุดต่ออายุอัตโนมัติ', exact: true }).click();
  await expect(page.getByRole('button', { name: 'หยุดต่ออายุอัตโนมัติ', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'ตรวจผลการต่ออายุ', exact: true })).toHaveCount(0);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: info.outputPath(`billing-renewal-clean-${width}.png`), fullPage: true });
  await page.getByRole('button', { name: 'ยืนยันหยุดต่ออายุ', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'ยืนยันหยุดการต่ออายุแล้ว' })).toBeVisible();
  await scenario.selectOption('capacity');
  await plans.getByRole('button', { name: 'เลือกแพ็กเกจนี้', exact: true }).first().click();
  await expect(page.getByRole('heading', { name: 'เลือกสาขาและผู้ใช้ที่จะคงสิทธิ์', exact: true })).toBeVisible();
  await page.getByLabel('ฉันตรวจสอบรายการที่คงไว้และรายการที่จะพักแล้ว', { exact: true }).check();
  await page.getByRole('button', { name: 'ใช้การเลือกนี้และตรวจสอบราคา', exact: true }).click();
  await expect(page.getByRole('heading', { name: /^ยืนยันซื้อ/ })).toBeVisible();
  await scenario.selectOption('quote-error');
  await plans.getByRole('button', { name: 'เลือกแพ็กเกจนี้', exact: true }).first().click();
  await expect(page.getByRole('alert').filter({ hasText: 'รายการหมดอายุหรือข้อมูลเปลี่ยน' })).toBeVisible();
  await plans.getByRole('button', { name: 'เลือกแพ็กเกจนี้', exact: true }).first().click();
  await expect(page.getByRole('heading', { name: /^ยืนยันซื้อ/ })).toBeVisible();
  for (const value of ['pending', 'activating', 'failed', 'held', 'expired', 'upgrade']) {
    await scenario.selectOption(value);
    await expect(page.getByRole('navigation', { name: 'หมวดแพ็กเกจและการชำระเงิน', exact: true })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
  }
  await page.getByRole('button', { name: 'การต่ออายุและชำระเงิน', exact: true }).click();
  await page.getByRole('button', { name: /^ตรวจลดเป็น/ }).first().click();
  await page.getByLabel('ฉันตรวจสอบรายการที่คงไว้และรายการที่จะพักแล้ว', { exact: true }).check();
  await page.getByRole('button', { name: 'ใช้การเลือกนี้และตรวจสอบราคา', exact: true }).click();
  await page.getByRole('button', { name: 'ยืนยันลดแพ็กเกจสิ้นรอบ', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'ยืนยันลดแพ็กเกจสิ้นรอบแล้ว' })).toBeVisible();
  await scenario.selectOption('start');
  await expect(plans).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: info.outputPath(`billing-preview-plans-${width}.png`), fullPage: true });
  expect(forbiddenRequests).toEqual([]);
  await page.getByRole('link', { name: 'ออกจากพรีวิว', exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`/companies/${companyId}/billing$`));
  await expect(page.getByRole('heading', { name: 'พรีวิวทุกขั้นตอน · เฉพาะ local', exact: true })).toHaveCount(0);
});
