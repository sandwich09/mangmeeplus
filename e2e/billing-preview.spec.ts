const packageControl = (card: Locator) => card.locator('input[name="offer"]');
async function backToPackages(page: Page) {
  const plans = page.getByRole('region', { name: 'เลือกแพ็กเกจ', exact: true });
  const back = page.getByRole('button', { name: /^(กลับ|กลับไปเลือกแพ็กเกจ)$/ });
  for (let i = 0; i < 3; i++) {
    await expect(plans.or(back).first()).toBeVisible();
    if (await plans.count()) break;
    await back.click();
  }
  await expect(plans).toBeVisible();
}
async function finishQuote(page: Page) {
  await expect(page.locator('[data-form-action-bar] button[aria-busy="true"]')).toHaveCount(0);
  const methods = page.getByRole('region', { name: 'วิธีจ่าย', exact: true });
  const tick = methods.getByRole('checkbox');
  if (await tick.count()) {
    // Every fresh quote still requires an unchecked consent, even after coming back.
    await expect(tick).not.toBeChecked();
    await expect(methods.getByRole('alert')).toHaveCount(0);
    await expect(tick).toBeInViewport();
    await page.getByRole('button', { name: 'ถัดไป', exact: true }).click();
    await expect(methods.getByRole('alert')).toHaveText('ติ๊กยอมรับการต่ออายุก่อน');
    await tick.check();
    await page.getByRole('button', { name: 'ถัดไป', exact: true }).click();
  }
}
async function choosePackage(page: Page, card: Locator, mode: BillingPurchaseMode = 'CARD_AUTO') {
  await backToPackages(page);
  await packageControl(card).check();
  await page.getByRole('button', { name: 'ถัดไป', exact: true }).click();
  await chooseBillingMethod(page, mode);
  await page.getByRole('button', { name: 'ถัดไป', exact: true }).click();
  await finishQuote(page);
}
