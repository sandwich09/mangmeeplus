import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { documentPreviewKind } from './DocumentPreviewModal';

const source = readFileSync(join(dirname(fileURLToPath(import.meta.url)), 'DocumentPreviewModal.tsx'), 'utf8');

describe('documentPreviewKind', () => {
  it('allows only the image and PDF formats accepted or generated by the product', () => {
    assert.equal(documentPreviewKind('image/png'), 'image');
    assert.equal(documentPreviewKind('IMAGE/JPEG; charset=binary'), 'image');
    assert.equal(documentPreviewKind('image/svg+xml'), 'image');
    assert.equal(documentPreviewKind('application/pdf'), 'pdf');
  });

  it('rejects other browser-renderable content instead of treating every image/* value as safe', () => {
    assert.equal(documentPreviewKind('image/gif'), 'unsupported');
    assert.equal(documentPreviewKind('image/webp'), 'unsupported');
    assert.equal(documentPreviewKind('text/html'), 'unsupported');
    assert.equal(documentPreviewKind(''), 'unsupported');
  });
});

describe('DocumentPreviewModal media lifecycle', () => {
  it('acknowledges viewing only from a successful media load and exposes render failure/retry paths', () => {
    assert.match(source, /onLoad=\{handleMediaLoad\}/);
    assert.match(source, /onError=\{handleMediaError\}/);
    assert.match(source, /if \(viewedRef\.current\) return;/);
    assert.match(source, /onViewedRef\.current\?\.\(\)/);
    assert.match(source, /data-preview-status=\{status\}/);
    assert.match(source, /onClick=\{\(\) => void retry\(\)\}/);
  });

  it('keeps tall images scrollable at a readable width and gives PDFs a useful viewport', () => {
    assert.match(source, /overflow-auto/);
    assert.match(source, /style=\{\{ width: `\$\{zoom\}%` \}\}/);
    assert.match(source, /h-auto max-w-none flex-none/);
    assert.match(source, /h-\[calc\(100dvh-12rem\)\]/);
    assert.doesNotMatch(source, /max-h-\[7[05]vh\]/);
  });

  it('does not offer direct new-tab navigation for SVG documents', () => {
    assert.match(source, /kind !== 'unsupported'/);
    assert.match(source, /!== 'image\/svg\+xml'/);
    assert.match(source, /mayOpenNewTab && source\.url/);
  });
});
