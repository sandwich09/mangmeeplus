import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { createHash, randomUUID } from 'node:crypto';
import { LocalStorageAdapter } from './local-storage.adapter';

describe('LocalStorageAdapter', () => {
  it('does not expose raw object keys in local URLs', async () => {
    const storage = new LocalStorageAdapter();
    const objectKey = 'co-1/123_file.pdf';

    const upload = await storage.createUploadIntent({
      companyId: 'co-1',
      objectKey,
      mimeType: 'application/pdf',
      byteSize: 1024,
    });
    const download = await storage.createDownloadUrl({ bucket: upload.bucket, objectKey });

    assert.equal(upload.uploadUrl.includes(objectKey), false);
    assert.equal(download.url.includes(objectKey), false);
  });

  it('persists and reads local upload bytes', async () => {
    const storage = new LocalStorageAdapter();
    const objectKey = `co-1/${randomUUID()}_receipt.png`;
    const upload = await storage.createUploadIntent({
      companyId: 'co-1',
      objectKey,
      mimeType: 'image/png',
      byteSize: 4,
    });
    const token = upload.uploadUrl.split('/').at(-1)!;

    await storage.storeUpload(token, Buffer.from('test'));

    assert.deepEqual(await storage.getObject({ bucket: upload.bucket, objectKey }), { bytes: Buffer.from('test') });
    const checksumSha256 = createHash('sha256').update('test').digest('hex');
    assert.deepEqual(await storage.getObjectMetadata({ bucket: upload.bucket, objectKey }), {
      byteSize: 4,
      checksumSha256,
      objectVersionId: checksumSha256,
      exists: true,
    });
  });

  it('rejects reuse of the same upload token instead of overwriting evidence bytes', async () => {
    const storage = new LocalStorageAdapter();
    const objectKey = `co-1/${randomUUID()}_receipt.png`;
    const upload = await storage.createUploadIntent({ companyId: 'co-1', objectKey, mimeType: 'image/png', byteSize: 4 });
    const token = upload.uploadUrl.split('/').at(-1)!;

    await storage.storeUpload(token, Buffer.from('test'));
    await assert.rejects(() => storage.storeUpload(token, Buffer.from('evil')), (error: any) => error?.code === 'EEXIST');
    assert.deepEqual(await storage.getObject({ bucket: upload.bucket, objectKey }), { bytes: Buffer.from('test') });
  });

  it('puts and idempotently deletes server-generated bytes', async () => {
    const storage = new LocalStorageAdapter();
    const objectKey = `co-1/${randomUUID()}_evidence.svg`;
    const checksumSha256 = createHash('sha256').update('artifact').digest('hex');

    const stored = await storage.putObject({ objectKey, mimeType: 'image/svg+xml', bytes: Buffer.from('artifact') });

    assert.deepEqual(stored, {
      bucket: 'local-attachments',
      objectKey,
      storageProvider: 'local',
      byteSize: 8,
      checksumSha256,
      objectVersionId: checksumSha256,
    });
    assert.deepEqual(await storage.getObject({ bucket: stored.bucket, objectKey }), { bytes: Buffer.from('artifact') });

    await storage.deleteObject({ bucket: stored.bucket, objectKey });
    await storage.deleteObject({ bucket: stored.bucket, objectKey });
    assert.deepEqual(await storage.getObjectMetadata({ bucket: stored.bucket, objectKey }), { byteSize: 0, exists: false });
  });

  it('returns a complete exact inventory without mutating local bytes', async () => {
    const storage = new LocalStorageAdapter();
    const objectKey = `co-1/${randomUUID()}_inventory.pdf`;
    const stored = await storage.putObject({ objectKey, mimeType: 'application/pdf', bytes: Buffer.from('artifact') });

    assert.deepEqual(await storage.getExactObjectVersionInventory({ bucket: stored.bucket, objectKey }), {
      bucket: 'local-attachments',
      objectKey,
      objectLockConfiguration: 'DISABLED',
      versions: [{
        versionId: stored.objectVersionId,
        isLatest: true,
        byteSize: 8,
        objectLockMetadataVerified: true,
      }],
      deleteMarkers: [],
      pagesScanned: 1,
      complete: true,
    });
    assert.deepEqual(await storage.getObject({ bucket: stored.bucket, objectKey }), { bytes: Buffer.from('artifact') });
  });
});
